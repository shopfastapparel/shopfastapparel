def main():
    print("1. Reading src/lib/blog.ts...")
    with open(BLOG_TS_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    ts_entry = f"""  {{
    slug: {json.dumps(post_data["slug"])},
    title: {json.dumps(post_data["title"])},
    description: {json.dumps(post_data["description"])},
    category: {json.dumps(post_data["category"])},
    city: {json.dumps(post_data["city"])},
    read_minutes: {post_data["read_minutes"]},
    published_at: {json.dumps(post_data["published_at"])},
    author: {json.dumps(post_data["author"])},
    cover_gradient: {json.dumps(post_data["cover_gradient"])},
    cover_emoji: {json.dumps(post_data["cover_emoji"])},
    cover_image_url: {json.dumps(post_data["cover_image_url"])},
    cover_image_credit: {json.dumps(post_data["cover_image_credit"])},
    keywords: {json.dumps(post_data["keywords"])},
    body: {json.dumps(post_data["body"])},
  }},
"""

    marker = "export const BLOG_POSTS: BlogPost[] = ["
    if marker not in content:
        raise ValueError(f"Marker '{marker}' not found in {BLOG_TS_PATH}")

    updated_content = content.replace(marker, f"{marker}\n{ts_entry}", 1)

    print("2. Writing updated src/lib/blog.ts...")
    with open(BLOG_TS_PATH, "w", encoding="utf-8") as f:
        f.write(updated_content)
    print("   ✅ Successfully updated src/lib/blog.ts!")

    print("3. Syncing to Supabase blog_posts table via REST API...")
    url = os.environ.get("SUPABASE_URL") or os.environ.get("VITE_SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY") or os.environ.get("VITE_SUPABASE_ANON_KEY")

    if not url or not key:
        raise ValueError("Missing Supabase credentials in .env")

    supabase_headers = {
        "apikey": key,
        "Authorization": f"Bearer {key}",
        "Content-Type": "application/json",
        "Prefer": "resolution=merge-duplicates"
    }

    db_payload = {
        "slug": post_data["slug"],
        "title": post_data["title"],
        "description": post_data["description"],
        "category": post_data["category"],
        "city": post_data["city"],
        "read_minutes": post_data["read_minutes"],
        "published_at": f"{post_data['published_at']}T00:00:00+00:00",
        "author": post_data["author"],
        "cover_gradient": post_data["cover_gradient"],
        "cover_emoji": post_data["cover_emoji"],
        "cover_image_url": post_data["cover_image_url"],
        "cover_image_credit": post_data["cover_image_credit"],
        "keywords": post_data["keywords"],
        "body": post_data["body"],
        "status": "published"
    }

    res = requests.post(
        f"{url}/rest/v1/blog_posts",
        headers=supabase_headers,
        json=db_payload,
        timeout=15
    )

    if res.status_code in [200, 201, 204]:
        print(f"   ✅ Successfully synced post to Supabase! Status: {res.status_code}")
    else:
        print(f"   ❌ Supabase API error ({res.status_code}): {res.text}")
        raise RuntimeError(f"Failed to sync post to Supabase: {res.text}")

    print("\n✨ Blog publishing workflow completed successfully!")

if __name__ == "__main__":
    main()
