def publish_to_blog_ts():
    blog_ts_path = os.path.join(PROJECT_ROOT, "src", "lib", "blog.ts")
    with open(blog_ts_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Check if slug already exists
    if f'slug: "{blog_post["slug"]}"' in content or f'slug: \'{blog_post["slug"]}\'' in content:
        print(f"⚠️ Post with slug '{blog_post['slug']}' already exists in src/lib/blog.ts. Skipping duplicate insert.")
        return True

    marker = "export const BLOG_POSTS: BlogPost[] = ["
    if marker not in content:
        print("❌ Marker not found in src/lib/blog.ts")
        return False

    ts_entry = f"""  {{
    slug: {json.dumps(blog_post["slug"])},
    title: {json.dumps(blog_post["title"])},
    description: {json.dumps(blog_post["description"])},
    category: {json.dumps(blog_post["category"])},
    city: {json.dumps(blog_post["city"])},
    read_minutes: {blog_post["read_minutes"]},
    published_at: {json.dumps(blog_post["published_at"])},
    author: {json.dumps(blog_post["author"])},
    cover_gradient: {json.dumps(blog_post["cover_gradient"])},
    cover_emoji: {json.dumps(blog_post["cover_emoji"])},
    cover_image_url: {json.dumps(blog_post["cover_image_url"])},
    cover_image_credit: {json.dumps(blog_post["cover_image_credit"])},
    keywords: {json.dumps(blog_post["keywords"])},
    body: {json.dumps(blog_post["body"])},
  }},
"""

    new_content = content.replace(marker, marker + "\n" + ts_entry, 1)
    with open(blog_ts_path, "w", encoding="utf-8") as f:
        f.write(new_content)

    print("✅ Successfully added auto detailing post to src/lib/blog.ts!")
    return True

def publish_to_supabase():
    if not SUPABASE_URL or not SUPABASE_KEY:
        print("⚠️ Supabase credentials missing from .env. Skipping DB publish.")
        return False

    headers = {
        "apikey": SUPABASE_KEY,
        "Authorization": f"Bearer {SUPABASE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "resolution=merge-duplicates"
    }

    payload = {
        "slug": blog_post["slug"],
        "title": blog_post["title"],
        "description": blog_post["description"],
        "category": blog_post["category"],
        "city": blog_post["city"],
        "read_minutes": blog_post["read_minutes"],
        "published_at": blog_post["published_at"],
        "author": blog_post["author"],
        "cover_gradient": blog_post["cover_gradient"],
        "cover_emoji": blog_post["cover_emoji"],
        "cover_image_url": blog_post["cover_image_url"],
        "cover_image_credit": blog_post["cover_image_credit"],
        "keywords": blog_post["keywords"],
        "body": blog_post["body"],
        "status": "published"
    }

    try:
        url = f"{SUPABASE_URL}/rest/v1/blog_posts?on_conflict=slug"
        res = requests.post(url, headers=headers, json=payload, timeout=12)
        if res.status_code in [200, 201]:
            print(f"✅ Successfully published '{blog_post['slug']}' to Supabase blog_posts table!")
            return True
        else:
            print(f"⚠️ Supabase publish status {res.status_code}: {res.text}")
            return False
    except Exception as e:
        print(f"❌ Failed to publish to Supabase: {e}")
        return False

